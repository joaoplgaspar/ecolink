-- ECOLINK no Supabase — 5: LOJA DE RECOMPENSAS (troca de EcoPontos)
--
-- O custo vem do CATÁLOGO no banco (nunca do que o navegador mandou) e o saldo
-- é recalculado no momento do resgate, com a conta TRAVADA (select … for update):
-- dois cliques ao mesmo tempo não gastam o mesmo saldo duas vezes.

create table public.recompensas (
  id bigint primary key,
  nome text not null,
  parceiro text not null,
  custo integer not null check (custo > 0),
  ativa boolean not null default true
);

create table public.resgates (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.perfis (id),
  recompensa_id bigint not null references public.recompensas (id),
  nome text not null,
  parceiro text not null,
  custo integer not null check (custo > 0),
  codigo text not null unique,
  em timestamptz not null default now()
);
create index resgates_usuario on public.resgates (usuario_id);

alter table public.recompensas enable row level security;
alter table public.resgates enable row level security;
revoke insert, update, delete, truncate, references, trigger on public.recompensas, public.resgates from anon, authenticated;
create policy recompensas_ler on public.recompensas for select using (ativa);
create policy resgates_ler on public.resgates for select using (usuario_id = auth.uid() or privado.eh_plataforma());

create or replace function public.resgatar(p_recompensa bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  eu public.perfis;
  r public.recompensas;
  saldo integer;
  novo public.resgates;
  alfabeto constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  c text;
begin
  -- Trava a linha da conta: resgates simultâneos da mesma pessoa entram em fila.
  select * into eu from public.perfis where id = auth.uid() for update;
  if eu.id is null or eu.status <> 'ativo' or not ('cidadao' = any (eu.papeis)) then
    perform privado.erro(403, 'Entre no perfil Cidadão para usar a loja.');
  end if;
  select * into r from public.recompensas where id = p_recompensa and ativa;
  if r.id is null then perform privado.erro(404, 'Recompensa não encontrada.'); end if;
  select coalesce(sum(valor), 0) into saldo from public.extrato where usuario_id = eu.id;
  if saldo < r.custo then
    perform privado.erro(422, format('Saldo insuficiente: faltam %s EcoPontos.', r.custo - saldo));
  end if;
  loop
    c := (select string_agg(substr(alfabeto, 1 + (get_byte(b, i) % 32), 1), '')
          from extensions.gen_random_bytes(8) b, generate_series(0, 7) i);
    c := 'ECO-' || substr(c, 1, 4) || '-' || substr(c, 5);
    exit when not exists (select 1 from public.resgates where codigo = c);
  end loop;
  insert into public.resgates (usuario_id, recompensa_id, nome, parceiro, custo, codigo)
  values (eu.id, r.id, r.nome, r.parceiro, r.custo, c) returning * into novo;
  insert into public.extrato (usuario_id, tipo, valor, referencia_tipo, referencia_id, descricao, criado_por)
  values (eu.id, 'resgate', -r.custo, 'resgate', novo.id, r.nome, eu.id);
  perform privado.notificar(eu.id, 'recompensa', '🎁', format('Recompensa resgatada: %s. Código: %s.', r.nome, novo.codigo));
  perform privado.auditar('resgate.criado', 'resgate', novo.id::text, jsonb_build_object('custo', r.custo));
  return to_jsonb(novo);
end $$;

revoke execute on function public.resgatar(bigint) from public, anon;
grant execute on function public.resgatar(bigint) to authenticated;
