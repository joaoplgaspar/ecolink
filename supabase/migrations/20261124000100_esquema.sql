-- ECOLINK no Supabase — 1/4: ESQUEMA
--
-- Espelha as coleções do modo local (src/data) com os mesmos nomes de campo
-- (snake_case), para que o domínio em JavaScript (src/domain) continue valendo
-- sem mudanças. Etapa 1 da migração: a jornada central da entrega
-- (contas, pontos, agendamento, recebimento, pesagem, extrato, notificações).

-- ------------------------------------------------------------------ contas --

-- Perfil público/privado de cada conta do Supabase Auth (auth.users).
-- PAPÉIS e STATUS nunca vêm do cliente: só funções do servidor os alteram.
create table public.perfis (
  id uuid primary key references auth.users (id) on delete cascade,
  nome text not null check (char_length(nome) between 2 and 80),
  email text not null,
  telefone text check (char_length(telefone) <= 20),
  cidade text check (char_length(cidade) <= 60),
  papeis text[] not null default '{cidadao}',
  status text not null default 'ativo' check (status in ('ativo', 'suspenso', 'excluido')),
  ultimo_perfil text check (ultimo_perfil in ('cidadao', 'parceiro', 'admin')),
  codigo_pessoal text unique,
  boas_vindas jsonb not null default '{}',
  aceite_termos jsonb,
  criado_em timestamptz not null default now(),
  constraint papeis_validos check (
    papeis <@ array['cidadao', 'parceiro_gestor', 'parceiro_operador', 'moderador', 'admin']
  )
);

-- Catálogo de materiais (fator de EcoPontos por kg), o mesmo de src/domain/materiais.js.
create table public.materiais (
  slug text primary key,
  rotulo text not null,
  fator integer not null check (fator > 0)
);

-- ------------------------------------------------------- parceiros e pontos --

create table public.organizacoes (
  id bigint generated by default as identity primary key,
  nome text not null,
  tipo text not null,
  documento text,
  responsavel_id uuid references public.perfis (id),
  status text not null default 'rascunho'
    check (status in ('rascunho', 'em_analise', 'ajustes', 'aprovada', 'reprovada', 'suspensa')),
  criado_em timestamptz not null default now()
);

create table public.pontos (
  id bigint generated by default as identity primary key,
  organizacao_id bigint references public.organizacoes (id),
  nome text not null check (char_length(nome) between 3 and 80),
  descricao text,
  endereco text not null,
  cidade text not null,
  latitude double precision,
  longitude double precision,
  instrucoes_acesso text,
  materiais text[] not null default '{}',
  regras_materiais jsonb not null default '{}',
  horarios jsonb not null default '{}', -- { "seg": [{ "abre": "08:00", "fecha": "18:00" }], ... }
  excecoes jsonb not null default '[]', -- [{ "data": "2026-12-25", "fechado": true, "motivo": "Natal" }]
  regras jsonb not null default '{}',   -- janela_min, capacidade_janela, antecedencia_horas, aceite_automatico, prazo_resposta_horas
  fotos jsonb not null default '[]',
  status text not null default 'rascunho'
    check (status in ('rascunho', 'em_analise', 'reprovado', 'ativo', 'pausado', 'suspenso', 'encerrado')),
  criado_em timestamptz not null default now(),
  aprovado_em timestamptz
);

-- Equipe de cada ponto (gestor/operador).
create table public.membros (
  id bigint generated by default as identity primary key,
  ponto_id bigint not null references public.pontos (id) on delete cascade,
  usuario_id uuid not null references public.perfis (id) on delete cascade,
  papel text not null check (papel in ('gestor', 'operador')),
  ativo boolean not null default true,
  desde date not null default current_date,
  unique (ponto_id, usuario_id)
);

-- ------------------------------------------------------------------ coletas --

create table public.coletas (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  usuario_id uuid not null references public.perfis (id),
  ponto_id bigint not null references public.pontos (id),
  tipo text not null default 'agendada' check (tipo in ('agendada', 'avulsa')),
  data date not null,
  janela_inicio text,
  janela_fim text,
  -- [{ material, kg_declarado, kg_aferido, status: pendente|aprovado|rejeitado, motivo }]
  itens jsonb not null default '[]',
  status text not null default 'solicitada' check (
    status in ('solicitada', 'confirmada', 'em_conferencia', 'concluida', 'rejeitada', 'recusada',
               'expirada', 'cancelada', 'nao_compareceu', 'contestada', 'ajustada')
  ),
  motivo text,
  responder_ate timestamptz,
  criada_em timestamptz not null default now(),
  atualizada_em timestamptz not null default now(),
  confirmada_em timestamptz,
  concluida_em timestamptz,
  cancelada_por text,
  cancelamento_tardio boolean not null default false,
  operador_pesagem_id uuid references public.perfis (id),
  pontos_creditados integer not null default 0,
  comprovante jsonb,
  lembrete_enviado boolean not null default false
);
create index coletas_ponto_data on public.coletas (ponto_id, data);
create index coletas_usuario on public.coletas (usuario_id);

-- O CÓDIGO DE ENTREGA fica numa tabela à parte: só o dono da coleta lê.
-- (Na tabela coletas, a equipe do ponto veria a linha inteira — e o código junto.)
create table public.coleta_codigos (
  coleta_id bigint primary key references public.coletas (id) on delete cascade,
  codigo_entrega text not null check (codigo_entrega ~ '^[0-9]{4}$'),
  tentativas integer not null default 0,
  bloqueado_ate timestamptz
);

-- Linha do tempo: toda transição da máquina de estados vira um evento.
create table public.coleta_eventos (
  id bigint generated by default as identity primary key,
  coleta_id bigint not null references public.coletas (id) on delete cascade,
  acao text not null,
  de text,
  para text not null,
  ator text not null check (ator in ('cidadao', 'ponto', 'sistema', 'moderacao')),
  ator_id uuid references public.perfis (id),
  motivo text,
  em timestamptz not null default now()
);
create index coleta_eventos_coleta on public.coleta_eventos (coleta_id);

-- ----------------------------------------------- extrato (livro-caixa) etc. --

-- Só de inclusão: ninguém edita nem apaga lançamentos (nem por política, nem por grant).
create table public.extrato (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.perfis (id),
  tipo text not null check (tipo in ('credito_coleta', 'resgate', 'ajuste', 'estorno', 'bonus')),
  valor integer not null check (valor <> 0),
  referencia_tipo text,
  referencia_id bigint,
  descricao text not null default '',
  criado_por uuid references public.perfis (id),
  em timestamptz not null default now()
);
create index extrato_usuario on public.extrato (usuario_id);

create table public.notificacoes (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.perfis (id) on delete cascade,
  tipo text not null,
  icone text,
  texto text not null,
  ref text,
  lida boolean not null default false,
  em timestamptz not null default now()
);
create index notificacoes_usuario on public.notificacoes (usuario_id, lida);

-- Avaliações VERIFICADAS (ligadas a uma entrega conferida).
create table public.avaliacoes (
  id bigint generated by default as identity primary key,
  ponto_id bigint not null references public.pontos (id),
  usuario_id uuid not null references public.perfis (id),
  usuario_nome text not null, -- já reduzido ("Ana R."): minimização
  coleta_id bigint references public.coletas (id),
  verificada boolean not null default false,
  nota integer not null check (nota between 1 and 5),
  tags text[] not null default '{}',
  comentario text not null default '' check (char_length(comentario) <= 500),
  resposta jsonb,
  removida jsonb,
  em timestamptz not null default now(),
  criada_em timestamptz not null default now(),
  unique (coleta_id, usuario_id)
);

-- Log de auditoria (inclui tentativas negadas). Escrito só por funções do servidor.
create table public.auditoria (
  id bigint generated by default as identity primary key,
  ator_id uuid references public.perfis (id),
  acao text not null,
  recurso_tipo text,
  recurso_id text,
  detalhes jsonb,
  em timestamptz not null default now()
);
