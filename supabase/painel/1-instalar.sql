-- =================== 20261124000100_esquema.sql ===================
-- ECOLINK no Supabase — 1/4: ESQUEMA
--
-- Espelha as coleções do modo local (src/data) com os mesmos nomes de campo
-- (snake_case), para que o domínio em JavaScript (src/domain) continue valendo
