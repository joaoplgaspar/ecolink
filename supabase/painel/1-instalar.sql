-- ------------------------------------------------------------------ contas --

-- Perfil público/privado de cada conta do Supabase Auth (auth.users).
-- PAPÉIS e STATUS nunca vêm do cliente: só funções do servidor os alteram.
create table public.perfis (
  id uuid primary key references auth.users (id) on delete cascade,
  nome text not null check (char_length(nome) between 2 and 80),
  email text not null,
  telefone text check (char_length(telefone) <= 20),
  cidade text check (char_length(cidade) <= 60),
  papeis text[] not null default '{cidadao}',
  status text not null default 'ativo' check (status in ('ativo', 'suspenso', 'excluido')),
  ultimo_perfil text check (ultimo_perfil in ('cidadao', 'parceiro', 'admin')),
  codigo_pessoal text unique,
  boas_vindas jsonb not null default '{}',
  aceite_termos jsonb,
  criado_em timestamptz not null default now(),
  constraint papeis_validos check (
    papeis <@ array['cidadao', 'parceiro_gestor', 'parceiro_operador', 'moderador', 'admin']
  )
);

-- Catálogo de materiais (fator de EcoPontos por kg), o mesmo de src/domain/materiais.js.
create table public.materiais (
  slug text primary key,
  rotulo text not null,
  fator integer not null check (fator > 0)
);

-- ------------------------------------------------------- parceiros e pontos --

create table public.organizacoes (
  id bigint generated by default as identity primary key,
  nome text not null,
  tipo text not null,
  documento text,
  responsavel_id uuid references public.perfis (id),
  status text not null default 'rascunho'
    check (status in ('rascunho', 'em_analise', 'ajustes', 'aprovada', 'reprovada', 'suspensa')),
  criado_em timestamptz not null default now()
);

create table public.pontos (
  id bigint generated by default as identity primary key,
  organizacao_id bigint references public.organizacoes (id),
  nome text not null check (char_length(nome) between 3 and 80),
  descricao text,
  endereco text not null,
  cidade text not null,
  latitude double precision,
  longitude double precision,
  instrucoes_acesso text,
  materiais text[] not null default '{}',
  regras_materiais jsonb not null default '{}',
  horarios jsonb not null default '{}', -- { "seg": [{ "abre": "08:00", "fecha": "18:00" }], ... }
  excecoes jsonb not null default '[]', -- [{ "data": "2026-12-25", "fechado": true, "motivo": "Natal" }]
  regras jsonb not null default '{}',   -- janela_min, capacidade_janela, antecedencia_horas, aceite_automatico, prazo_resposta_horas
  fotos jsonb not null default '[]',
  status text not null default 'rascunho'
    check (status in ('rascunho', 'em_analise', 'reprovado', 'ativo', 'pausado', 'suspenso', 'encerrado')),
  criado_em timestamptz not null default now(),
  aprovado_em timestamptz
);

-- Equipe de cada ponto (gestor/operador).
create table public.membros (
  id bigint generated by default as identity primary key,
  ponto_id bigint not null references public.pontos (id) on delete cascade,
  usuario_id uuid not null references public.perfis (id) on delete cascade,
  papel text not null check (papel in ('gestor', 'operador')),
  ativo boolean not null default true,
  desde date not null default current_date,
  unique (ponto_id, usuario_id)
);

-- ------------------------------------------------------------------ coletas --

